from datetime import date
from fastapi import APIRouter, Depends
from sqlmodel import Session, select
from backend.app.database import get_session
from backend.app.models import DailyChallenge
from backend.app.analytics import fetch_transactions_df, compute_spending_summary
from backend.app.llm import generate_recommendations_llm

router = APIRouter(prefix="/api/recommendations", tags=["recommendations"])

@router.get("")
def get_recommendations(session: Session = Depends(get_session)):
    """
    Returns grounded financial coach insights generated by AI from computed metrics.
    No raw personal data or PII is sent to the LLM.
    """
    df = fetch_transactions_df(session)
    metrics = compute_spending_summary(df)
    insights_data = generate_recommendations_llm(metrics)
    return insights_data

@router.get("/daily-challenge")
def get_daily_challenge(session: Session = Depends(get_session)):
    """Fetch today's active gamified micro-challenge."""
    today_str = date.today().strftime("%Y-%m-%d")
    challenge = session.exec(select(DailyChallenge).where(DailyChallenge.date == today_str)).first()
    if not challenge:
        challenge = DailyChallenge(
            date=today_str,
            title="Cook at home today: Skip Swiggy & Zomato",
            potential_saving=450.0,
            completed=False
        )
        session.add(challenge)
        session.commit()
        session.refresh(challenge)
    return challenge

@router.post("/daily-challenge/toggle")
def toggle_daily_challenge(session: Session = Depends(get_session)):
    """Toggle completion status for today's challenge."""
    today_str = date.today().strftime("%Y-%m-%d")
    challenge = session.exec(select(DailyChallenge).where(DailyChallenge.date == today_str)).first()
    if challenge:
        challenge.completed = not challenge.completed
        session.add(challenge)
        session.commit()
        session.refresh(challenge)
        return challenge
    return {"message": "No challenge found"}

